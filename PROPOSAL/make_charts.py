# G1 -- lead time: formation-velocity traces + operating-point trade-off
# --------------------------------------------------------------------------
def g1_lead_time(lt: dict):
    chosen = lt["chosen"]
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11.0, 4.2),
                                   gridspec_kw={"wspace": 0.32})
    for rid, tr in sorted(lt["ring_trace"].items(), key=lambda kv: int(kv[0])):
        days = [int(d) for d in tr]
        al = [tr[str(d)] for d in days]
        ax1.plot(days, al, lw=1.4, alpha=0.75)
        comp = int(lt["completion_day"][str(rid)])
        ax1.axvline(comp, color=ORANGE, lw=0.8, ls=":", alpha=0.7)
    ax1.set_xlabel("Day since portfolio start", fontsize=9)
    ax1.set_ylabel("L4 ring score (0–1)", fontsize=9)
    ax1.set_title("Formation velocity: ring score vs. completion\n"
                  "(orange dotted = ring's last application)",
                  fontsize=9.5)

    # --- right panel: only annotate Pareto-frontier points to avoid overlap ---
    sweep = lt["sweep"]
    all_bc = [r["before_completion"] for r in sweep]
    all_apw = [r["alerts_per_week"] for r in sweep]
    ax2.scatter(all_apw, all_bc, s=24, color=GREY, alpha=0.5, zorder=2)

    # Pick Pareto-frontier: for each distinct bc value, pick the lowest apw
    frontier = {}
    for r in sweep:
        bc = r["before_completion"]
        apw = r["alerts_per_week"]
        if bc not in frontier or apw < frontier[bc]["alerts_per_week"]:
            frontier[bc] = r
    # Annotate only frontier points (max ~6-7, well-spaced by y)
    for bc, r in sorted(frontier.items()):
        apw = r["alerts_per_week"]
        lab = f"L4≥{r['threshold']:.2f}, n≥{r['min_size']}"
        ax2.scatter([apw], [bc], s=50, color=TEAL, zorder=3, alpha=0.9)
        # offset labels to the right to avoid bar overlap
        ax2.annotate(lab, (apw, bc), fontsize=7, color=NAVY,
                     xytext=(8, 0), textcoords="offset points",
                     va="center")

    # highlight the chosen strict point
    ax2.scatter([chosen["alerts_per_week"]], [chosen["before_completion"]],
                s=90, color=ORANGE, zorder=4, marker="*",
                label=f"Strict: 0 false alarms, {chosen['median_lead']:.0f}d lead")
    ax2.legend(fontsize=7.5, loc="lower right", frameon=True, framealpha=0.9)
    ax2.set_xlabel("False clusters / week (analyst load)", fontsize=9)
    ax2.set_ylabel("Rings caught before completion (of 9)", fontsize=9)
    ax2.set_title("Recall vs. analyst load trade-off", fontsize=9.5)

    fig.suptitle("Catch a forming ring before it finishes filing",
                 fontsize=11, fontweight="bold", y=1.01)
    fig.tight_layout(rect=[0, 0, 1, 0.97])
    fig.savefig(CHARTS / "g1_lead_time.png")
    plt.close(fig)


