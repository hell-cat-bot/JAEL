# G5 -- financial hockey stick with Monte-Carlo band
# --------------------------------------------------------------------------
def g5_financial(fin: dict):
    base, up = fin["base"], fin["upside"]
    yrs = [r["year"] for r in base]
    nets = [r["net"] for r in base]
    nets_u = [r["net_upside"] for r in up]
    mc = fin["mc"]
    x = np.arange(len(yrs))
    fig, ax = plt.subplots(figsize=(7.6, 4.6))
    ax.plot(x, nets, marker="o", color=NAVY, lw=2.2,
            label="Base (loss avoided + recovery)")
    ax.plot(x, nets_u, marker="s", ls="--", color=TEAL, lw=1.8,
            label="Upside: growth-unlock of throttled segments")
    lo_years = [mc["net_y1"][0], None, mc["net_y3"][0], None, mc["net_y5"][0]]
    hi_years = [mc["net_y1"][2], None, mc["net_y3"][2], None, mc["net_y5"][2]]
    for xi, lo, hi in zip(x, lo_years, hi_years):
        if lo is not None:
            ax.vlines(xi, lo, hi, color=GREY, lw=5, alpha=0.35)
    ax.axhline(0, color="k", lw=0.8)
    # Annotate base values — stagger Y4/Y5 to avoid overlap
    for xi, nb, nu in zip(x, nets, nets_u):
        # base annotation below the dot if positive and close to upside
        if xi >= 3 and abs(nb - nu) < 15:  # Y4, Y5: stagger
            ax.text(xi - 0.15, nb - 3.5, f"₹{nb:+.0f}", ha="center",
                    fontsize=8.5, fontweight="bold", color=NAVY)
            ax.text(xi + 0.15, nu + 2.5, f"₹{nu:+.0f}", ha="center",
                    fontsize=8.5, fontweight="bold", color=TEAL)
        else:
            ax.text(xi, nb + 2.5, f"₹{nb:+.0f}", ha="center",
                    fontsize=8.5, fontweight="bold", color=NAVY)
            if abs(nu - nb) > 3:
                ax.text(xi, nu + 2.5, f"₹{nu:+.0f}", ha="center",
                        fontsize=8.5, fontweight="bold", color=TEAL)
    ax.set_xticks(x, yrs)
    ax.set_ylabel("Net P&L impact (₹ crore)", fontsize=9.5)
    npv_b, npv_u = fin['npv_base'], fin['npv_upside']
    prob = fin['mc']['p_npv_positive']
    ax.set_title(f"Year-1 build cost → Year-3 profitability\n"
                 f"Base NPV ₹{npv_b:+.0f} cr  ·  "
                 f"Upside ₹{npv_u:+.0f} cr  ·  "
                 f"P(NPV>0) = {prob:.0%}",
                 fontsize=10, fontweight="bold", pad=10)
    ax.legend(frameon=True, framealpha=0.9, fontsize=8, loc="upper left")
    # Footnote — broken into two lines
    ax.text(0.0, -0.16,
            "Anchors [audited AR Note 18, FY26]: target book Vehicles+CD "
            "₹19,029 cr (NPA 2.12%), write-offs ₹437 cr, AUM ₹30,639 cr.",
            transform=ax.transAxes, fontsize=7.5, color=GREY)
    ax.text(0.0, -0.22,
            "Assumptions: ring share 20% [A2], prevention 50% [A3], "
            "recovery uplift 10% [A4]. Grey bands = Monte-Carlo 90% CI.",
            transform=ax.transAxes, fontsize=7.5, color=GREY)
    fig.tight_layout(rect=[0, 0.05, 1, 1])
    fig.savefig(CHARTS / "g5_financial.png")
    plt.close(fig)


