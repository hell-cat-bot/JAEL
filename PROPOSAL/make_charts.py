# G3 -- relation ablation (what moves the risk score most)
# --------------------------------------------------------------------------
def g3_ablation():
    full = 0.7540   # notebook section 8a, fixed-param node+graph GBT
    drops = [("account", 0.5374), ("device", 0.5494), ("dealer", 0.6558),
             ("guarantor", 0.6735), ("person", 0.7407)]
    fig, ax = plt.subplots(figsize=(6.6, 3.0))
    names = [d[0] for d in drops]
    hits = [full - v for v in [d[1] for d in drops]]
    ax.barh(names, hits, color=[TEAL, NAVY, ORANGE, GREY, "#C4A747"])
    for i, h in enumerate(hits):
        ax.text(h + 0.003, i, f"{h:.3f}", va="center", fontsize=8)
    ax.axvline(0, color="k", lw=0.8)
    ax.set_xlabel("drop in AUCPR when this relation's features are removed")
    ax.set_title("G3 - Which connection signals matter most?\n"
                 "Removing one relation at a time [COLAB, ring-disjoint]")
    fig.tight_layout()
    fig.savefig(CHARTS / "g3_ablation.png")
    plt.close(fig)


