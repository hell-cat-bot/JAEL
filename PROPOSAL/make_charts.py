    ax.text(0, gaps[0] + 0.019, "AUCPR", ha="center", fontsize=8.5, color=GREY)
    ax.text(1, gaps[1] + 0.005, f"+{gaps[1]:.1%}", ha="center",
            fontweight="bold", fontsize=13, color=TEAL)
    ax.text(1, gaps[1] + 0.019, "AUCPR", ha="center", fontsize=8.5, color=GREY)
    ax.set_ylim(0, max(gaps) * 1.5)
    ax.set_ylabel("AUCPR gap when a naive split leaks", fontsize=9)
    ax.set_title("Why evaluation honesty matters: the leakage gap",
                 fontsize=10.5, fontweight="bold", pad=12)
