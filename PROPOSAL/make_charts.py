# G8 -- dealer fairness: TVS's own audited books show dealers repay
# --------------------------------------------------------------------------
def g8_dealer_fairness():
    data = TVS.npa_by_sector()
    order = sorted(data, key=data.get)            # lowest NPA first
    vals = [data[k] for k in order]
    dealer = "Advance to dealers"
    target = set(TVS.TARGET_SEGMENTS)
    colors = [GREEN if k == dealer else
              (NAVY if k in target else GREY) for k in order]
    fig, ax = plt.subplots(figsize=(8.0, 4.6))
    bars = ax.barh(order, vals, color=colors, height=0.65)
    for b, k in zip(bars, order):
        v = data[k]
        ax.text(v + 0.15, b.get_y() + b.get_height() / 2,
                f"{v:.2f}%", va="center", fontsize=8.5,
                fontweight="bold" if k in (dealer,) or k in target else "normal",
                color=GREEN if k == dealer else "black")
    ax.axvline(data[dealer], color=GREEN, lw=1.2, ls=":", alpha=0.8)
    ax.set_xlabel("Gross NPA as % of exposure, FY26 (audited)", fontsize=9)
    ax.set_xlim(0, 12.2)
    ax.set_title("TVS's audited books: dealer advances carry only 0.23% NPA\n"
                 "Dealers repay — blocking them punishes rural customers",
                 fontweight="bold", fontsize=10, pad=10)
    # Footnote — use fig.text to avoid collision with x-axis label
    fig.text(0.08, 0.06,
            "Navy = dealer-sourced pilot book (Vehicles 2.64% + CD 1.02% "
            "= ₹19,029 cr @ 2.12%).", fontsize=7.5, color=GREY)
    fig.text(0.08, 0.02,
            "Tested two ways: audited books (0.23% NPA) + our ablation "
            "(dealer = LEAST signal, −0.10 AUCPR). "
            "Same verdict → conduit, not cause.", fontsize=7.5, color=GREY)
    fig.tight_layout(rect=[0, 0.10, 1, 1])
    fig.savefig(CHARTS / "g8_dealer_fairness.png")
    plt.close(fig)


